// base/term/tio.h
#ifndef TIO_H
#define TIO_H

#include <stdarg.h>
#include <stdint.h>

// ==================== ИНИЦИАЛИЗАЦИЯ ====================

/**
 * Инициализирует глобальный терминал.
 * Вызывается один раз из main.c после term_init().
 */
void tio_init(void* term_ptr);

/**
 * Проверяет, инициализирован ли терминал.
 * Возвращает 1 если да, 0 если нет.
 */
int tio_initialized(void);

// ==================== БАЗОВЫЙ ВЫВОД ====================

/**
 * Форматированный вывод в терминал (поддерживает %d, %x, %s, %p и т.д.)
 * Потокобезопасно.
 */
void tio_printf(const char* fmt, ...) __attribute__((format(printf, 1, 2)));

/**
 * Форматированный вывод с готовым va_list.
 * Для внутреннего использования или если уже есть va_list.
 */
void tio_vprintf(const char* fmt, va_list args);

/**
 * Вывод строки без форматирования.
 */
void tio_puts(const char* s);

/**
 * Вывод одного символа.
 */
void tio_putc(char c);

// ==================== УПРАВЛЕНИЕ ЭКРАНОМ ====================

/**
 * Очищает экран терминала.
 */
void tio_clear(void);

/**
 * Устанавливает цвет текста (RGB).
 * Пример: tio_set_color(255, 0, 0); // красный текст
 */
void tio_set_color(uint8_t r, uint8_t g, uint8_t b);

// ==================== УПРАВЛЕНИЕ ПРОМПТОМ ====================

/**
 * Включает режим командной строки (показывает промпт).
 */
void tio_enable_prompt(void);

/**
 * Выключает режим командной строки.
 */
void tio_disable_prompt(void);

/**
 * Устанавливает текст промпта (например "> " или "root@alk:~$ ").
 */
void tio_set_prompt(const char* text);

// ==================== БЛОКИРОВКИ ====================

/**
 * Захватывает внутреннюю блокировку терминала.
 * Нужно для длительных операций, чтобы не блокировать каждый вызов.
 */
void tio_lock(void);

/**
 * Освобождает внутреннюю блокировку терминала.
 */
void tio_unlock(void);

#endif // TIO_H